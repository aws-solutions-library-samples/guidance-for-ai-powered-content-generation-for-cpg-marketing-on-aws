# Fully unattended: no prompts, no interactive input.
# Usage in a CodeBuild buildspec:
#   commands:
#     - chmod +x scripts/test-guidance-deploy.sh
#     - ./scripts/test-guidance-deploy.sh

set -euo pipefail

# ============================================
# CONFIGURATION
# ============================================
AWS_REGION="us-east-1"
STACK_NAME="ContentGenStack-$(date +%s)"
EMAIL_ADDRESS="deployments-ignore@example.com"
NODE_VERSION="20"
DESTROY_AFTER_TEST="${DESTROY_AFTER_TEST:-true}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
CDK_DIR="${PROJECT_ROOT}/cdk"

echo "============================================================"
echo " Guidance sample code validation - Content Generation on AWS"
echo "============================================================"
echo "Stack name : ${STACK_NAME}"
echo "Region     : ${AWS_REGION}"
echo "Test email : ${EMAIL_ADDRESS}"

# ============================================
# ENVIRONMENT SETUP
# ============================================
echo ""
echo "=== Environment setup ==="
export AWS_REGION="${AWS_REGION}"
export AWS_DEFAULT_REGION="${AWS_REGION}"
export STACK_NAME="${STACK_NAME}"
export CI=true

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
export CDK_DEFAULT_ACCOUNT="${ACCOUNT_ID}"
export CDK_DEFAULT_REGION="${AWS_REGION}"
echo "Account ID: ${ACCOUNT_ID}"
echo "Region:     ${AWS_REGION}"
echo "Caller:     $(aws sts get-caller-identity --query Arn --output text)"

# ============================================
# INSTALL DEPENDENCIES
# ============================================
echo ""
echo "=== Installing system dependencies ==="
if command -v n >/dev/null 2>&1; then
  n "${NODE_VERSION}" || echo "n failed; keeping the pre-installed Node.js"
elif command -v nvm >/dev/null 2>&1; then
  nvm install "${NODE_VERSION}" && nvm use "${NODE_VERSION}"
fi
echo "Node.js: $(node -v)"
echo "npm:     $(npm -v)"
echo "AWS CLI: $(aws --version 2>&1)"

echo ""
echo "=== Installing AWS CDK CLI ==="
npm install -g aws-cdk@2.1121.0
echo "CDK: $(cdk --version)"

echo ""
echo "=== Installing frontend dependencies ==="
cd "${PROJECT_ROOT}"
npm install --no-audit --no-fund

echo ""
echo "=== Building the React frontend ==="
npm run build
if [ ! -d "${PROJECT_ROOT}/dist" ]; then
  echo "ERROR: frontend build did not produce ./dist" >&2
  exit 1
fi
ls -la "${PROJECT_ROOT}/dist"

echo ""
echo "=== Installing CDK project dependencies ==="
cd "${CDK_DIR}"
npm install --no-audit --no-fund

# ============================================
# CDK BOOTSTRAP CHECK
# ============================================
echo ""
echo "=== CDK bootstrap check ==="
CDK_BOOTSTRAP_STACK="$(aws cloudformation describe-stacks --region "${AWS_REGION}" \
  --query "Stacks[?StackName=='CDKToolkit'].StackName" --output text 2>/dev/null || true)"
if [ -z "${CDK_BOOTSTRAP_STACK}" ] || [ "${CDK_BOOTSTRAP_STACK}" = "None" ]; then
  echo "Running CDK bootstrap for aws://${ACCOUNT_ID}/${AWS_REGION}"
  cdk bootstrap "aws://${ACCOUNT_ID}/${AWS_REGION}"
else
  echo "CDK already bootstrapped (${CDK_BOOTSTRAP_STACK})"
fi

# ============================================
# SYNTH
# ============================================
echo ""
echo "=== Synthesizing the CDK app ==="
cd "${CDK_DIR}"
cdk synth --quiet

echo ""
echo "=== Asserting no credential material is present in the template ==="
# The admin credential must be generated by AWS Secrets Manager, never rendered
# into the template. Fail the build if a password-like property reappears.
if grep -RniE '"(TemporaryPassword|Password)"[[:space:]]*:' "${CDK_DIR}/cdk.out"/*.template.json; then
  echo "ERROR: a password property was found in the synthesized template" >&2
  exit 1
fi
if grep -RnE 'COGNITO_PASSWORD' "${CDK_DIR}/cdk.out"/*.template.json; then
  echo "ERROR: COGNITO_PASSWORD was found in the synthesized template" >&2
  exit 1
fi
echo "No credential material in the template."

echo ""
echo "=== Asserting no wildcard Bedrock or Lambda grants ==="
python3 - <<'PY'
import glob
import json
import sys

problems = []
for template_path in glob.glob('cdk.out/*.template.json'):
    with open(template_path) as handle:
        template = json.load(handle)
    for name, resource in template.get('Resources', {}).items():
        if resource.get('Type') != 'AWS::IAM::Policy':
            continue
        doc = resource.get('Properties', {}).get('PolicyDocument', {})
        for statement in doc.get('Statement', []):
            actions = statement.get('Action', [])
            actions = [actions] if isinstance(actions, str) else actions
            resources = statement.get('Resource', [])
            resources = [resources] if isinstance(resources, str) else resources
            flat = [r for r in resources if isinstance(r, str)]
            for action in actions:
                if not isinstance(action, str):
                    continue
                if action.startswith('bedrock:') and '*' in flat:
                    problems.append(f'{name}: {action} on *')
                if action == 'lambda:InvokeFunction':
                    for r in flat:
                        if r.endswith(':function:*'):
                            problems.append(f'{name}: {action} on {r}')

if problems:
    print('ERROR: over-broad IAM grants found:', file=sys.stderr)
    for p in problems:
        print(f'  {p}', file=sys.stderr)
    sys.exit(1)
print('No wildcard Bedrock or account-wide Lambda invoke grants.')
PY

echo ""
echo "=== Asserting the frontend / API / handler field contracts agree ==="
# GenerateTextRequest sets additionalProperties: false, and the asset upload is a
# presigned POST. Both couple the frontend to the backend in ways that typecheck,
# lint, synth and ASH all consider valid. Catch the drift before deploying.
python3 "${PROJECT_ROOT}/scripts/verify-field-contract.py"

# ============================================
# DEPLOYMENT
# ============================================
echo ""
echo "=== Deploying ${STACK_NAME} ==="
cd "${CDK_DIR}"
cdk deploy --all --require-approval never \
  --outputs-file "${PROJECT_ROOT}/cdk-outputs.json"

# ============================================
# VALIDATION
# ============================================
echo ""
echo "=== Validating deployment ==="

STACK_STATUS="$(aws cloudformation describe-stacks --region "${AWS_REGION}" \
  --stack-name "${STACK_NAME}" --query 'Stacks[0].StackStatus' --output text)"
echo "Stack status: ${STACK_STATUS}"
if [ "${STACK_STATUS}" != "CREATE_COMPLETE" ] && [ "${STACK_STATUS}" != "UPDATE_COMPLETE" ]; then
  echo "ERROR: unexpected stack status ${STACK_STATUS}" >&2
  exit 1
fi

get_output() {
  aws cloudformation describe-stacks --region "${AWS_REGION}" \
    --stack-name "${STACK_NAME}" \
    --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text
}

WEBSITE_URL="$(get_output WebsiteUrl)"
API_URL="$(get_output ApiUrl)"
USER_POOL_ID="$(get_output UserPoolId)"
USER_POOL_CLIENT_ID="$(get_output UserPoolClientId)"
SECRET_NAME="$(get_output AdminCredentialSecretName)"

echo "WebsiteUrl:        ${WEBSITE_URL}"
echo "ApiUrl:            ${API_URL}"
echo "UserPoolId:        ${USER_POOL_ID}"
echo "UserPoolClientId:  ${USER_POOL_CLIENT_ID}"
echo "SecretName:        ${SECRET_NAME}"

for required in "${WEBSITE_URL}" "${API_URL}" "${USER_POOL_ID}" "${USER_POOL_CLIENT_ID}" "${SECRET_NAME}"; do
  if [ -z "${required}" ] || [ "${required}" = "None" ]; then
    echo "ERROR: a required stack output is missing" >&2
    exit 1
  fi
done

echo ""
echo "--- Checking Lambda functions are Active ---"
LAMBDA_COUNT=0
for fn in $(aws cloudformation describe-stack-resources --region "${AWS_REGION}" \
    --stack-name "${STACK_NAME}" \
    --query "StackResources[?ResourceType=='AWS::Lambda::Function'].PhysicalResourceId" \
    --output text); do
  STATE="$(aws lambda get-function-configuration --region "${AWS_REGION}" \
    --function-name "${fn}" --query 'State' --output text)"
  echo "  ${fn}: ${STATE}"
  LAMBDA_COUNT=$((LAMBDA_COUNT + 1))
done
echo "Lambda functions found: ${LAMBDA_COUNT}"

echo ""
echo "--- Checking the 4 DynamoDB tables are ACTIVE with PITR ---"
for tbl in $(aws cloudformation describe-stack-resources --region "${AWS_REGION}" \
    --stack-name "${STACK_NAME}" \
    --query "StackResources[?ResourceType=='AWS::DynamoDB::Table'].PhysicalResourceId" \
    --output text); do
  STATUS="$(aws dynamodb describe-table --region "${AWS_REGION}" \
    --table-name "${tbl}" --query 'Table.TableStatus' --output text)"
  PITR="$(aws dynamodb describe-continuous-backups --region "${AWS_REGION}" \
    --table-name "${tbl}" \
    --query 'ContinuousBackupsDescription.PointInTimeRecoveryDescription.PointInTimeRecoveryStatus' \
    --output text)"
  echo "  ${tbl}: ${STATUS}, PITR=${PITR}"
  if [ "${PITR}" != "ENABLED" ]; then
    echo "ERROR: point-in-time recovery is not enabled on ${tbl}" >&2
    exit 1
  fi
done

echo ""
echo "--- Retrieving the generated admin credential from Secrets Manager ---"
ADMIN_SECRET="$(aws secretsmanager get-secret-value --region "${AWS_REGION}" \
  --secret-id "${SECRET_NAME}" --query SecretString --output text)"
if [ -z "${ADMIN_SECRET}" ] || [ "${ADMIN_SECRET}" = "None" ]; then
  echo "ERROR: could not read the admin credential from Secrets Manager" >&2
  exit 1
fi
echo "Credential retrieved (length ${#ADMIN_SECRET}, value not printed)"

echo ""
echo "--- Checking the Cognito admin user ---"
aws cognito-idp admin-get-user --region "${AWS_REGION}" \
  --user-pool-id "${USER_POOL_ID}" --username admin \
  --query 'UserStatus' --output text

echo ""
echo "--- Authenticating against Cognito ---"
ID_TOKEN="$(aws cognito-idp initiate-auth --region "${AWS_REGION}" \
  --auth-flow USER_PASSWORD_AUTH \
  --client-id "${USER_POOL_CLIENT_ID}" \
  --auth-parameters "USERNAME=admin,PASSWORD=${ADMIN_SECRET}" \
  --query 'AuthenticationResult.IdToken' --output text)"
if [ -z "${ID_TOKEN}" ] || [ "${ID_TOKEN}" = "None" ]; then
  echo "ERROR: Cognito authentication failed" >&2
  exit 1
fi
echo "Obtained an ID token (length ${#ID_TOKEN})"

echo ""
echo "--- Verifying the API rejects unauthenticated requests ---"
UNAUTH_CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST \
  -H 'Content-Type: application/json' \
  -d '{"content_type":"email","input":"test"}' \
  "${API_URL}generate-text" || echo "000")"
echo "Unauthenticated POST /generate-text -> HTTP ${UNAUTH_CODE}"
if [ "${UNAUTH_CODE}" != "401" ] && [ "${UNAUTH_CODE}" != "403" ]; then
  echo "ERROR: API did not reject an unauthenticated request (got ${UNAUTH_CODE})" >&2
  exit 1
fi

echo ""
echo "--- Verifying request validation rejects an over-long prompt ---"
LONG_PROMPT="$(head -c 5000 < /dev/zero | tr '\0' 'a')"
VALIDATION_CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST \
  -H 'Content-Type: application/json' \
  -H "Authorization: ${ID_TOKEN}" \
  -d "{\"content_type\":\"email\",\"input\":\"${LONG_PROMPT}\"}" \
  "${API_URL}generate-text" || echo "000")"
echo "Authenticated POST with a 5000-character input -> HTTP ${VALIDATION_CODE}"
if [ "${VALIDATION_CODE}" != "400" ]; then
  echo "ERROR: API Gateway request validation did not reject an over-long prompt" >&2
  exit 1
fi

echo ""
echo "--- Verifying authenticated data access is tenant-scoped ---"
CREATE_BODY='{"name":"validation-product","category":"test","description":"created by CI"}'
CREATED="$(curl -s -X POST \
  -H 'Content-Type: application/json' \
  -H "Authorization: ${ID_TOKEN}" \
  -d "${CREATE_BODY}" \
  "${API_URL}products")"
echo "POST /products -> ${CREATED}"
PRODUCT_ID="$(echo "${CREATED}" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("id",""))')"
if [ -z "${PRODUCT_ID}" ]; then
  echo "ERROR: product creation did not return an id" >&2
  exit 1
fi

LISTED="$(curl -s -H "Authorization: ${ID_TOKEN}" "${API_URL}products")"
echo "GET /products returned $(echo "${LISTED}" | python3 -c 'import json,sys; print(len(json.load(sys.stdin).get("products",[])))') item(s)"
if ! echo "${LISTED}" | grep -q "${PRODUCT_ID}"; then
  echo "ERROR: created product not visible to its owner" >&2
  exit 1
fi
if echo "${LISTED}" | grep -q '"owner"'; then
  echo "ERROR: the tenant key leaked into the API response" >&2
  exit 1
fi

curl -s -o /dev/null -X DELETE -H "Authorization: ${ID_TOKEN}" \
  "${API_URL}products/${PRODUCT_ID}"
echo "Cleaned up the validation product."

echo ""
echo "--- Verifying the brand profile round-trips per user ---"
curl -s -o /dev/null -X POST \
  -H 'Content-Type: application/json' \
  -H "Authorization: ${ID_TOKEN}" \
  -d '{"content":"Voice: plain-spoken. Never hype."}' \
  "${API_URL}brand-profile"
PROFILE="$(curl -s -H "Authorization: ${ID_TOKEN}" "${API_URL}brand-profile")"
if ! echo "${PROFILE}" | grep -q "plain-spoken"; then
  echo "ERROR: brand profile did not round-trip" >&2
  exit 1
fi
echo "Brand profile round-trip OK."

echo ""
echo "--- Checking the CloudFront-hosted SPA ---"
for attempt in 1 2 3 4 5 6; do
  SITE_CODE="$(curl -s -o /dev/null -w '%{http_code}' "${WEBSITE_URL}" || echo "000")"
  echo "  attempt ${attempt}: HTTP ${SITE_CODE}"
  [ "${SITE_CODE}" = "200" ] && break
  sleep 20
done
if [ "${SITE_CODE}" != "200" ]; then
  echo "ERROR: SPA did not return HTTP 200 from ${WEBSITE_URL}" >&2
  exit 1
fi

echo ""
echo "--- Checking security response headers ---"
HEADERS="$(curl -sI "${WEBSITE_URL}")"
for header in "strict-transport-security" "x-content-type-options" "x-frame-options"; do
  if ! echo "${HEADERS}" | tr 'A-Z' 'a-z' | grep -q "${header}"; then
    echo "ERROR: missing response header ${header}" >&2
    exit 1
  fi
  echo "  ${header}: present"
done

echo ""
echo "--- Checking the injected runtime config ---"
CONFIG_CODE="$(curl -s -o /tmp/config.json -w '%{http_code}' "${WEBSITE_URL}/config.json" || echo "000")"
echo "GET /config.json -> HTTP ${CONFIG_CODE}"
if [ "${CONFIG_CODE}" = "200" ]; then
  cat /tmp/config.json; echo ""
else
  echo "ERROR: config.json was not served" >&2
  exit 1
fi

echo ""
echo "Deployment validated successfully!"

# ============================================
# TEARDOWN
# ============================================
if [ "${DESTROY_AFTER_TEST}" = "true" ]; then
  echo ""
  echo "=== Tearing down ${STACK_NAME} ==="
  cd "${CDK_DIR}"
  cdk destroy --all --force
  echo "Teardown complete."
else
  echo ""
  echo "DESTROY_AFTER_TEST=false - leaving ${STACK_NAME} in place."
  echo "Remove it later with:"
  echo "  cd cdk && STACK_NAME=${STACK_NAME} cdk destroy --all --force"
fi

echo ""
echo "Deployment completed successfully!"
